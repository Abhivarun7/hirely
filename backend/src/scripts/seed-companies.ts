function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

async function getOrCreateSkillTag(name: string): Promise<mongoose.Types.ObjectId> {
  const existing = await SkillTag.findOne({ name });
  if (existing) return existing._id as mongoose.Types.ObjectId;
  const created = await SkillTag.create({ name, slug: slugify(name) });
  return created._id as mongoose.Types.ObjectId;
}

async function getOrCreateJobCategory(name: string): Promise<mongoose.Types.ObjectId> {
  const existing = await JobCategory.findOne({ name });
  if (existing) return existing._id as mongoose.Types.ObjectId;
  const created = await JobCategory.create({ name, slug: slugify(name) });
  return created._id as mongoose.Types.ObjectId;
}

function daysAgo(n: number): Date {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d;
}

async function seed(): Promise<void> {
  console.log('Seeding companies + jobs...\n');
  await connectDatabase();

  let companiesCreated = 0;
  let jobsCreated = 0;
  let jobsSkipped = 0;

  for (const c of companies) {
    // === Step 1: signup ===
    // Mirror authService.createUser for role=company_owner. The signup form
    // collects email + password + company_name (+ industry, which the auth
    // schema currently strips). We set is_email_verified=true here only
    // because seeds shouldn't require an email round-trip.
    let owner = await User.findOne({ email: c.owner.email });
    if (!owner) {
      const password_hash = await bcrypt.hash(c.owner.password, 12);
      owner = await User.create({
        email: c.owner.email,
        password_hash,
        role: 'company_owner',
        is_email_verified: true,
        is_active: true,
        is_banned: false,
        totp_enabled: false,
      });
      console.log(`  + Owner   ${c.owner.email}`);
    } else {
      console.log(`  - Owner   ${c.owner.email}  (already exists)`);
    }

    // Companies are created with the same minimal payload that
    // authService.createUser uses: { name, slug, approval_status: 'pending' }.
    // The Profile form fills in everything else after signup.
    let company = await Company.findOne({ slug: c.slug });
    let createdNow = false;
    if (!company) {
      company = await Company.create({
        name: c.name,
        slug: c.slug,
        approval_status: 'pending',
      });
      companiesCreated++;
      createdNow = true;
      console.log(`  + Company [${c.name}]  (signup payload)`);
    } else {
      console.log(`  - Company [${c.name}]  (already exists)`);
    }

    if (!owner.company_id) {
      owner.company_id = company._id as mongoose.Types.ObjectId;
      await owner.save();
    }

    if (createdNow) {
      // === Step 2: Profile-form fields ===
      // Same shape the company owner would submit via /company/profile.
      await Company.updateOne(
        { _id: company._id },
        {
          $set: {
            description: c.description,
            industry: c.industry,
            company_size: c.company_size,
            website_url: c.website_url,
            linkedin_url: c.linkedin_url,
            logo_url: c.logo_url,
          },
        }
      );

      // === Step 3: admin approval ===
      // Mirrors adminApi.approveCompany so the company is visible in seeker
      // search and home-feed nearby aggregations.
      await Company.updateOne(
        { _id: company._id },
        { $set: { approval_status: 'approved', approved_at: new Date() } }
      );
      // Reload so subsequent steps see the merged document.
      company = await Company.findById(company._id);
      if (!company) throw new Error(`Failed to reload company ${c.slug} after update`);
      console.log(`    profile filled + approved`);
    }

    // Branch
    let branch = await CompanyBranch.findOne({
      company_id: company._id,
      name: c.branch.name,
    });
    if (!branch) {
      branch = await CompanyBranch.create({
        company_id: company._id,
        name: c.branch.name,
        city: c.branch.city,
        state: c.branch.state,
        country: c.branch.country,
        address: c.branch.address,
        latitude: c.branch.latitude,
        longitude: c.branch.longitude,
        is_active: true,
      });
      console.log(`  + Branch  ${c.branch.name}`);
    } else {
      console.log(`  - Branch  ${c.branch.name}  (already exists)`);
    }

    // Jobs
    for (const j of c.jobs) {
      const existingJob = await Job.findOne({ company_id: company._id, title: j.title });
      if (existingJob) {
        console.log(`    - Job    ${j.title}  (already exists)`);
        jobsSkipped++;
        continue;
      }

      const categoryId = await getOrCreateJobCategory(j.category);

      const slug = `${slugify(j.title)}-${Math.random().toString(36).slice(2, 7)}`;
      const created = await Job.create({
        company_id: company._id,
        category_id: categoryId,
        posted_by: owner._id,
        job_ref: `${c.slug.toUpperCase()}-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
        title: j.title,
        slug,
        description: j.description,
        responsibilities: j.responsibilities,
        requirements: j.requirements,
        experience_level: j.experience_level,
        experience_min_years: j.experience_min_years,
        experience_max_years: j.experience_max_years,
        job_type: j.job_type,
        work_mode: j.work_mode,
        salary_min: j.salary_min,
        salary_max: j.salary_max,
        salary_currency: j.salary_currency,
        salary_disclosed: true,
        openings: 1,
        locations: [
          {
            branch_id: branch._id,
            label: `${c.branch.name} — ${c.branch.city}`,
            latitude: c.branch.latitude,
            longitude: c.branch.longitude,
            city: c.branch.city,
            state: c.branch.state,
            country: c.branch.country,
            address: c.branch.address,
            openings: 1,
            is_primary: true,
            geo: { type: 'Point', coordinates: [c.branch.longitude, c.branch.latitude] },
          },
        ],
        status: 'active',
        views_count: 0,
      });

      // Back-date so the home-feed nearby aggregation can find it
      const postedAt = daysAgo(j.posted_days_ago);
      await Job.updateOne({ _id: created._id }, { $set: { createdAt: postedAt, updatedAt: postedAt } });

      // Required + optional skills
      for (const skillName of j.required_skills) {
        const tagId = await getOrCreateSkillTag(skillName);
        try {
          await JobSkill.create({ job_id: created._id, skill_tag_id: tagId, is_required: true });
        } catch {
          // unique conflict — already linked
        }
      }
      for (const skillName of j.optional_skills) {
        const tagId = await getOrCreateSkillTag(skillName);
        try {
          await JobSkill.create({ job_id: created._id, skill_tag_id: tagId, is_required: false });
        } catch {
          // unique conflict — already linked
        }
      }

      console.log(`    + Job    ${j.title.padEnd(40)}  posted ${j.posted_days_ago}d ago`);
      jobsCreated++;
    }
  }

  console.log(
    `\n  Done -- ${companiesCreated} companies created (others skipped), ${jobsCreated} jobs created, ${jobsSkipped} jobs skipped.\n`
  );

  console.log('  Company-owner credentials:');
  for (const c of companies) {
    console.log(`    ${c.name.padEnd(10)}  ${c.owner.email}  /  ${c.owner.password}`);
  }
  console.log('');

  await disconnectDatabase();
}

seed().catch((err) => {
  console.error('Company seed failed:', err);
  mongoose.disconnect();
  process.exit(1);
});
