/**
 * Companies + jobs seed — creates 2 companies with 5 active jobs each.
 *
 * Mirrors the production company-onboarding flow:
 *   1. Owner user is created exactly like `authService.createUser` does for a
 *      company_owner registration (same field set as the signup form in
 *      `frontend/src/pages/auth/Register.tsx`).
 *   2. Company is created with the same minimal payload the signup uses
 *      (`name`, `slug`, `approval_status: 'pending'`), then "completed" with
 *      the editable fields exposed by the Company Profile form
 *      (`frontend/src/pages/company/Profile.tsx`): description, industry,
 *      company_size, website_url, linkedin_url, logo_url.
 *   3. Approval is flipped to `approved` to mirror an admin moderation
 *      action — without this the company won't surface in the public feeds.
 *
 * Field-set parity:
 *   - Industry values use the Profile form's capitalized list
 *     (Technology, Healthcare, Finance, Education, Manufacturing, Retail,
 *     Media, Transportation, Real Estate, Other) rather than free-form
 *     strings.
 *   - `company_size` values match the Company schema enum
 *     (`1-10`, `11-50`, `51-200`, `201-500`, `500+`).
 *   - `founding_year` is intentionally omitted — it's not in either form.
 *
 * Run with: npx tsx src/scripts/seed-companies.ts
 *
 * Safe to re-run:
 *   - Companies are matched by `slug` and reused if already present.
 *   - Owner users matched by email and reused.
 *   - Branches matched by (company_id, name) and reused.
 *   - Jobs matched by (company_id, title) and reused.
 *
 * Each job is back-dated within the last 14 days so they show up in the
 * "Companies hiring near you" home-feed section out of the box.
 */

