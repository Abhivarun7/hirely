interface JobSeed {
  title: string;
  description: string;
  responsibilities: string;
  requirements: string;
  experience_level: 'entry' | 'mid' | 'senior' | 'lead' | 'executive';
  experience_min_years: number;
  experience_max_years: number;
  job_type: 'full_time' | 'part_time' | 'contract' | 'internship' | 'freelance';
  work_mode: 'onsite' | 'remote' | 'hybrid';
  salary_min: number;
  salary_max: number;
  salary_currency: string;
  category: string;
  required_skills: string[];
  optional_skills: string[];
  posted_days_ago: number;
}

/**
 * Industry options mirror the Company Profile form. Anything outside this set
 * won't appear correctly in the form's <select>, so we constrain seeds to it.
 */
type Industry =
  | 'Technology'
  | 'Healthcare'
  | 'Finance'
  | 'Education'
  | 'Manufacturing'
  | 'Retail'
  | 'Media'
  | 'Transportation'
  | 'Real Estate'
  | 'Other';

/** Company.company_size enum from the Mongoose schema. */
type CompanySize = '1-10' | '11-50' | '51-200' | '201-500' | '500+';

interface CompanySeed {
  /** Sent by the signup form as `company_name`. */
  name: string;
  /** Auto-generated by `authService.createUser` from the name; pinned here so
   *  re-runs deterministically find the same company. */
  slug: string;
  /** From the Company Profile form. */
  industry: Industry;
  /** From the Company Profile form. */
  company_size: CompanySize;
  /** From the Company Profile form. */
  description: string;
  /** From the Company Profile form (`website` field, persisted as `website_url`). */
  website_url: string;
  /** From the Company Profile form (`linkedIn` field, persisted as `linkedin_url`). */
  linkedin_url?: string;
  /** From the Company Profile form (uploaded via `companyEndpoints.uploadLogo`). */
  logo_url?: string;
  /** Mirrors the auth signup payload (email + password). */
  owner: { email: string; password: string };
  /** Branches are managed separately by the company; not part of the signup or
   *  Profile form. We seed one default branch so jobs can be located. */
  branch: {
    name: string;
    city: string;
    state: string;
    country: string;
    address: string;
    latitude: number;
    longitude: number;
  };
  jobs: JobSeed[];
}

